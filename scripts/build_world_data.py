#!/usr/bin/env python3
"""
build_world_data.py - pack the rendered scenes' height maps for the 4D viewer (docs/world.html).

For every scene it reads scenes/scene_N_height.npy (float32 metres, 512 x 512, row 0 = north, 0.5 m/px) and the scene /
metadata files, stores a compact copy in data/heightmaps/<city>.npz (uint16 decimetres) and writes docs/assets/cities.js
(one JS file so the viewer also works when opened from disk, without a web server).

    python scripts/build_world_data.py --data data_real --results results --out-assets docs/assets --out-npz data/heightmaps
"""
import argparse
import base64
import json
import os
import zlib

import numpy as np


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", required=True, help="rendered OSM-derived dataset folder (metadata.jsonl, scenes/)")
    ap.add_argument("--results", default="results", help="folder with real_per_city.json (baseline accuracy per city)")
    ap.add_argument("--out-assets", default="docs/assets")
    ap.add_argument("--out-npz", default="data/heightmaps")
    args = ap.parse_args()

    meta = [json.loads(l) for l in open(os.path.join(args.data, "metadata.jsonl"))]
    per_city = {}
    p = os.path.join(args.results, "real_per_city.json")
    if os.path.exists(p):
        per_city = {r["city"]: r for r in json.load(open(p))["cities"]}

    os.makedirs(args.out_assets, exist_ok=True)
    os.makedirs(args.out_npz, exist_ok=True)
    cities = []
    seen = set()
    for m in meta:
        if m["scene"] in seen:
            continue
        seen.add(m["scene"])
        sc = m["scene"]
        doc = json.load(open(os.path.join(args.data, "scenes", f"scene_{sc}.json")))
        H = np.load(os.path.join(args.data, "scenes", f"scene_{sc}_height.npy")).astype(np.float32)
        dm = np.clip(np.rint(H * 10.0), 0, 65535).astype("<u2")
        np.savez_compressed(os.path.join(args.out_npz, f"{m['city']}.npz"), height_dm=dm, gsd=m["gsd_m"], lat=m["lat"], lon=m["lon"])
        payload = base64.b64encode(zlib.compress(dm.tobytes(), 9)).decode("ascii")
        dates = sorted({x["date"] for x in meta if x["scene"] == sc})
        pc = per_city.get(m["city"], {})
        cities.append({
            "id": m["city"], "scene": sc, "lat": m["lat"], "lon": m["lon"], "gsd": m["gsd_m"], "size": m["size_px"],
            "dates": dates, "nBuildings": doc["n_buildings"], "builtFraction": doc["built_fraction_of_field"],
            "explicitHeightFraction": doc["explicit_height_fraction"], "maxHeight": doc["max_height_m"],
            "baselineR1": pc.get("R1_acc"), "baselineR1Lo": pc.get("R1_ci_lo"), "baselineR1Hi": pc.get("R1_ci_hi"),
            "baselineR2": pc.get("R2_acc"), "nPairs": pc.get("R1_n"), "h": payload,
        })
    out = os.path.join(args.out_assets, "cities.js")
    with open(out, "w") as f:
        f.write("// generated by scripts/build_world_data.py - height maps are zlib-compressed little-endian uint16 decimetres\n")
        f.write("window.SC_CITIES = " + json.dumps(cities, separators=(",", ":")) + ";\n")
    print(f"{len(cities)} cities -> {out} ({os.path.getsize(out) / 1e6:.2f} MB), npz in {args.out_npz}")


if __name__ == "__main__":
    main()
